SELECT
  GROUPING_ID(CITY, CATEGORY_NAME, CHANNEL, GATEWAY, CURRENCY_CODE, TIER) AS GID,
f.CITY,
f.CATEGORY_NAME,
f.CHANNEL,
f.GATEWAY,
f.CURRENCY_CODE,
f.TIER,
SUM(CASE WHEN f.TXN_DAY = DATE '2026-10-20' THEN f.REVENUE_INR ELSE 0 END) AS CUR_VALUE,
  SUM(CASE WHEN f.TXN_DAY < DATE '2026-10-20' THEN f.REVENUE_INR ELSE 0 END) / 14 AS BASE_VALUE,
  COUNT(*) AS N_ROWS
FROM PIPE.FCT_REVENUE f
WHERE f.TXN_DAY >= ADD_DAYS(DATE '2026-10-20', -14) AND f.TXN_DAY <= DATE '2026-10-20'
GROUP BY CUBE (f.CITY, f.CATEGORY_NAME, f.CHANNEL, f.GATEWAY, f.CURRENCY_CODE, f.TIER);
